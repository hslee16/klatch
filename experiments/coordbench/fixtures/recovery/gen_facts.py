PLAUSIBLE = [[1, 0], [15, 15], [15, 0], [1, 1], [1, 15], [15, 14], [15, 1]]
ODD = [3, 5, 7, 9, 11, 13]


def draw(rng, avoid):
    while True:
        k, r = rng.choice(ODD), rng.randrange(1, 15)
        if [k, r] not in avoid:
            return k, r


def generate(seed=SEED):
    rng = random.Random(seed)
    k, r = draw(rng, PLAUSIBLE)
    sk, sr = draw(rng, PLAUSIBLE + [[k, r]])
